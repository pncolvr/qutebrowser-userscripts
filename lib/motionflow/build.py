"""Build the standalone userscript from its independently maintained modules."""

from pathlib import Path
import argparse

root = Path(__file__).resolve().parents[2]
source = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument(
    '--check', action='store_true', help='fail if generated artifacts are stale'
)
args = parser.parse_args()
header = '''// ==UserScript==
// @name         YouTube MotionFlow
// @namespace    qutebrowser-userscripts
// @version      3.2.1
// @description  Local RIFE smoothing, GPU Lanczos or optional AI upscaling, and audio compensation.
// @match        https://www.youtube.com/*
// @match        https://www.youtube-nocookie.com/embed/*
// @grant        none
// @qute-js-world user
// @run-at       document-end
// ==/UserScript==

// Generated by lib/motionflow/build.py. Edit the source modules, then rebuild.
// Independent implementation: no code from the original extension is included.
// Original project inspiration: Arunhari124's Live 60 fps converting extension for YouTube.
// https://github.com/Arunhari124/Live-60-fps-converting-extension-for-youtube
// Optional AI upscaling: Xintao Wang et al., Real-ESRGAN (BSD-3-Clause).
// https://github.com/xinntao/Real-ESRGAN
// Optional AI: RIFE 4.25 (hzwer), ONNX distribution via vs-mlrt, NVIDIA TensorRT-RTX.
'''

modules = ['worker.js', 'neural-worker.js', 'presenter.js', 'ui.js', 'settings.js', 'main.js']
for site, name in [('youtube', 'youtube-motionflow.js'), ('generic', 'video-motionflow.js')]:
    metadata = header
    if site == 'generic':
        metadata = metadata.replace(
            'YouTube MotionFlow', 'MotionFlow for video players'
        ).replace(
            '// @match        https://www.youtube.com/*\n// @match        https://www.youtube-nocookie.com/embed/*',
            '// @match        http://*/*\n// @match        https://*/*\n// @exclude      https://www.youtube.com/*\n// @exclude      https://www.youtube-nocookie.com/*',
        )
    text = (
        metadata
        + "\n(() => {\n'use strict';\nconst SITE = "
        + repr(site)
        + ";\n"
        + '\n'.join((source / name).read_text() for name in modules)
        + "\n})();\n"
    )
    target = root / 'custom/js' / name
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'MotionFlow bundles are stale; run python lib/motionflow/build.py\n')
    else:
        target.write_text(text)
